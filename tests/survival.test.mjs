import assert from 'node:assert/strict';
import * as THREE from 'three';
import { Player } from '../src/entities/player.js';
import { advanceEating } from '../src/entities/eating.js';
import { normalizeWorldSave } from '../src/save.js';

globalThis.document = new EventTarget();
globalThis.window = {};
const player = new Player({ edition: 'beta' }, new THREE.PerspectiveCamera(), { addEventListener() {} });
const flightWorld = { getBlock(_x, y) { return y === 0 || y === 4 ? 1 : 0; } };
player.pos.set(0.5, 1, 0.5);
assert.equal(player.toggleFlight(), false, 'Survival cannot toggle flight');
player.gameMode = 'creative';
assert.equal(player.flying, false, 'Creative enters on foot');
player.update(0.05, flightWorld, null);
assert.equal(player.onGround, true);
assert.equal(player.toggleFlight(), true);
player.setTouchKey(player.bindings.jump, true);
for (let i = 0; i < 15; i++) player.update(0.05, flightWorld, null);
assert.ok(player.pos.y > 1.5 && player.pos.y < 2.21, 'flight ascends but collides with a ceiling');
player.setTouchKey(player.bindings.jump, false);
assert.equal(player.toggleFlight(), false);
for (let i = 0; i < 15; i++) player.update(0.05, flightWorld, null);
assert.equal(player.onGround, true, 'disabling flight restores gravity');
player.gameMode = 'survival';
assert.equal(player.hunger, 20);
assert.equal(player.saturation, 5);
player.hunger = 12;
player.saturation = 0;
player.health = 10;
player.inventory[0] = { id: 297, count: 2, damage: 0 };
player.pointerLocked = true;
player.rightDown = true;
let eating = advanceEating({ id: 297 }, 1.5, player, null);
assert.equal(eating.completed, false, 'food is not consumed before the eating animation completes');
assert.equal(player.heldStack.count, 2);
eating = advanceEating(eating.eating, 0.11, player, null);
assert.equal(eating.completed, true);
assert.equal(player.hunger, 17, 'bread restores food rather than health');
assert.equal(player.health, 10);
assert.equal(player.saturation, 6);
assert.equal(player.heldStack.count, 1);
player.hunger = 20;
assert.equal(player.eatHeld(null), false, 'ordinary food cannot be consumed at full hunger');
assert.equal(player.heldStack.count, 1);
player.hunger = 10;
player.rightDown = false;
assert.equal(advanceEating({ id: 297, elapsed: 1 }, 1, player, null).eating, null, 'releasing use cancels eating');
player.rightDown = true;
player.pointerLocked = false;
player.touchActive = true;
assert.equal(advanceEating({ id: 297 }, 1.6, player, null).completed, true, 'touch controls can eat without pointer lock');

player.hunger = 18; player.saturation = 5; player.exhaustion = 0; player.health = 10;
player.updateHunger(4, 2, null);
assert.equal(player.health, 11, 'at least 18 hunger regenerates one health every four seconds');
assert.equal(player.exhaustion, 3, 'healing consumes food through exhaustion');
player.hunger = 17; player.health = 10;
player.updateHunger(4, 2, null);
assert.equal(player.health, 10, 'lower hunger prevents regeneration');
player.hunger = 10; player.saturation = 2; player.exhaustion = 4;
player.updateHunger(0.05, 2, null);
assert.equal(player.saturation, 1, 'exhaustion drains saturation before hunger');
assert.equal(player.hunger, 10);
player.saturation = 0; player.exhaustion = 4;
player.updateHunger(0.05, 2, null);
assert.equal(player.hunger, 9);
player.hunger = 0; player.health = 10; player.hurtTime = 0;
player.updateHunger(4, 1, null);
assert.equal(player.health, 10, 'Easy starvation cannot reduce health below ten');
player.updateHunger(4, 2, null);
assert.equal(player.health, 9, 'Normal starvation can damage above one health');
player.health = 1; player.hurtTime = 0;
player.updateHunger(4, 2, null);
assert.equal(player.health, 1, 'Normal starvation cannot kill');
player.updateHunger(4, 3, null);
assert.equal(player.dead, true, 'Hard starvation can kill');
player.respawn(64);
assert.equal(player.hunger, 20, 'respawn restores hunger');

const save = { version: 1, seed: 'survival', edits: [], player: {
  pos: [0, 64, 0], inventory: Array(36).fill(null), armor: Array(4).fill(null),
  hunger: 8, saturation: 3.5, exhaustion: 2.2,
} };
const restored = normalizeWorldSave(save);
assert.equal(restored.player.hunger, 8);
assert.equal(restored.player.saturation, 3.5);
assert.equal(restored.player.exhaustion, 2.2);
delete save.player.hunger; delete save.player.saturation; delete save.player.exhaustion;
assert.equal(normalizeWorldSave(save).player.hunger, 20, 'older saves start with full hunger');
console.log('ALL SURVIVAL TESTS PASSED');
